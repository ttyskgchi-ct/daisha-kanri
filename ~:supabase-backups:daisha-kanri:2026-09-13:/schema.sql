CREATE OR REPLACE FUNCTION "public"."check_double_booking"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    AS $$
BEGIN
    -- 保留やキャンセル、またはcar_idがNULL（保留中）の場合はチェックをスキップ
    IF NEW.status != '確定' OR NEW.car_id IS NULL THEN
        RETURN NEW;
    END IF;

    -- 同一車両で、期間が重複する『確定』の予約が既に存在するか検証
    IF EXISTS (
        SELECT 1 FROM daisha_reservations
        WHERE car_id = NEW.car_id
          AND status = '確定'
          AND id != NEW.id -- 自分自身は除外（更新時のため）
          AND start_at < NEW.end_at
          AND end_at > NEW.start_at
    ) THEN
        RAISE EXCEPTION '車両ID % は、指定された期間（% 〜 %）で既に他の予約が確定しています。ダブルブッキングのため登録できません。', 
            NEW.car_id, NEW.start_at, NEW.end_at;
    END IF;

    RETURN NEW;
END;
$$;


ALTER FUNCTION "public"."check_double_booking"() OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."process_daisha_reservation_audit"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    AS $$
BEGIN
    IF (TG_OP = 'DELETE') THEN
        INSERT INTO daisha_audit_logs(reservation_id, action, old_data)
        VALUES(OLD.id, 'DELETE', to_jsonb(OLD));
        RETURN OLD;
    ELSIF (TG_OP = 'UPDATE') THEN
        INSERT INTO daisha_audit_logs(reservation_id, action, old_data, new_data)
        VALUES(NEW.id, 'UPDATE', to_jsonb(OLD), to_jsonb(NEW));
        RETURN NEW;
    ELSIF (TG_OP = 'INSERT') THEN
        INSERT INTO daisha_audit_logs(reservation_id, action, new_data)
        VALUES(NEW.id, 'INSERT', to_jsonb(NEW));
        RETURN NEW;
    END IF;
    RETURN NULL;
END;
$$;


ALTER FUNCTION "public"."process_daisha_reservation_audit"() OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."purge_old_daisha_audit_logs"() RETURNS integer
    LANGUAGE "plpgsql"
    AS $$
DECLARE
    deleted_rows INT;
BEGIN
    DELETE FROM daisha_audit_logs
    WHERE created_at < NOW() - INTERVAL '90 days';
    
    GET DIAGNOSTICS deleted_rows = ROW_COUNT;
    RETURN deleted_rows;
END;
$$;


ALTER FUNCTION "public"."purge_old_daisha_audit_logs"() OWNER TO "postgres";

